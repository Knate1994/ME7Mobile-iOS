import Foundation

/// KWP2000 fault code: 2 bytes SAE (top 2 bits = P/C/B/U, then 4 hex digits) + status byte.
enum Dtc {
    static func code(_ hi: Int, _ lo: Int) -> String {
        let letters = Array("PCBU")
        return "\(letters[hi >> 6])\(hx((hi >> 4) & 3, 1))\(hx(hi & 0x0F, 1))\(hx(lo))"
    }

    /// Status byte (ISO 14230-3): bit 7 = MIL request, bits 6-5 = storage state. Raw bytes are always shown too.
    static func status(_ s: Int) -> String {
        let state: String
        switch (s >> 5) & 3 {
        case 3: state = "активна"
        case 2: state = "спорадическая"
        case 1: state = "сохранена, сейчас нет"
        default: state = "нет"
        }
        return s & 0x80 != 0 ? "\(state), лампа" : state
    }

    static func describe(_ hi: Int, _ lo: Int, _ st: Int) -> String {
        let c = code(hi, lo)
        let text = names[c].map { " — \($0)" } ?? ""
        return "\(c)\(text)\n   \(status(st))  [\(hx(hi)) \(hx(lo)) \(hx(st))]"
    }

